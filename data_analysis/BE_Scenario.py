#*6. Calculating Bioenergy Potentials (Ordonez et al. 2018 Methodology)

def calculate_bioenergy_emissions(df):
    try:
        # --- CONSTANTS (Ordonez et al. 2018 - Scenario S4) ---
        ETHANOL_YIELD_L_PER_MG = 88.5   # Liters Ethanol per Mg Sugarcane
        ETHANOL_DENSITY_KG_L   = 0.789  # Kg/L
        LHHV_MJ_KG             = 28.26  # Lower Heating Value (MJ/kg)
        
        # Emissions Factors (gCO2/MJ)
        # BASELINE (Fossil Fuel Substitution): Emissions avoided by replacing gasoline
        BASELINE_EMISSION_GASOLINE = 94.0 
        
        # LIFECYCLE (Bioenergy Production): Emissions generated by farming/processing
        BE_EMISSION_INTENSITY      = 31.1 
        
        # 1. Calculate Ethanol Production (Volume -> Mass -> Energy)
        df['Ethanol_Liters'] = df['Total_Cane_Mg'] * ETHANOL_YIELD_L_PER_MG
        df['Ethanol_Intracell_STD_Liters'] = df['Total_Cane_Intracell_STD_Mg'] * ETHANOL_YIELD_L_PER_MG
        
        df['Ethanol_Kg'] = df['Ethanol_Liters'] * ETHANOL_DENSITY_KG_L
        df['Ethanol_Intracell_STD_Kg'] = df['Ethanol_Intracell_STD_Liters'] * ETHANOL_DENSITY_KG_L
        
        df['Ethanol_MJ'] = df['Ethanol_Kg'] * LHHV_MJ_KG
        df['Ethanol_Intracell_STD_MJ'] = df['Ethanol_Intracell_STD_Kg'] * LHHV_MJ_KG
        
        # 2. Fossil Fuel Substitution (Gross Mitigation Potential)
        # This is the "Credit" for displacing gasoline
        df['Fossil_Fuel_Substitution_gCO2'] = df['Ethanol_MJ'] * BASELINE_EMISSION_GASOLINE
        df['Fossil_Fuel_Substitution_Intracell_STD_gCO2'] = df['Ethanol_Intracell_STD_MJ'] * BASELINE_EMISSION_GASOLINE
        
        # 3. Lifecycle Emissions (Bioenergy Production Cost)
        # This is the "Debit" for producing the biofuel
        df['Lifecycle_Emissions_BE_gCO2'] = df['Ethanol_MJ'] * BE_EMISSION_INTENSITY
        df['Lifecycle_Emissions_BE_Intracell_STD_gCO2'] = df['Ethanol_Intracell_STD_MJ'] * BE_EMISSION_INTENSITY
        
        # 4. Avoided Emissions (Net Mitigation Potential)
        # Net = Substitution - Lifecycle
        df['Avoided_Emissions_gCO2'] = df['Fossil_Fuel_Substitution_gCO2'] - df['Lifecycle_Emissions_BE_gCO2']
        df['Avoided_Emissions_Intracell_STD_gCO2'] = df['Fossil_Fuel_Substitution_Intracell_STD_gCO2'] - df['Lifecycle_Emissions_BE_Intracell_STD_gCO2']
        
        # 5. Convert to Megagrams (Mg CO2e) for final reporting
        df['Fossil_Fuel_Substitution_MgCO2'] = df['Fossil_Fuel_Substitution_gCO2'] / 10**6
        df['Lifecycle_Emissions_BE_MgCO2'] = df['Lifecycle_Emissions_BE_gCO2'] / 10**6
        df['Avoided_Emissions_BE_MgCO2'] = df['Avoided_Emissions_gCO2'] / 10**6
        df['Avoided_Emissions_BE_Intracell_STD_MgCO2'] = df['Avoided_Emissions_Intracell_STD_gCO2'] / 10**6
        
        # 6. Calculate Metric per Hectare (Mg CO2e/ha) for visualization
        df['Avoided_Emissions_BE_MgCO2_ha'] = 0.0
        mask = df['Coca_2022'] > 0
        df.loc[mask, 'Avoided_Emissions_BE_MgCO2_ha'] = (
            df.loc[mask, 'Avoided_Emissions_BE_MgCO2'] / df.loc[mask, 'Coca_2022']
        )

        print("Bioenergy calculations completed successfully.")
        
    except Exception as e:
        print(f"Error during calculation: {e}")
    return df

# Run Calculation
be_df = calculate_bioenergy_emissions(be_df)
