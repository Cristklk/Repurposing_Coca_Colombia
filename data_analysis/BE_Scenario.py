def export_data(df, filename):
    try:
        # Define clean columns for export including the 3 key metrics
        cols_to_keep = [
            'GRI_1K_F_1', 
            'Coca_2022',
            'Cane_Yield_Kg_ha',
            'Avoided_Emissions_BE_MgCO2_ha',
            'Fossil_Fuel_Substitution_MgCO2',
            'Lifecycle_Emissions_BE_MgCO2',
            'Avoided_Emissions_BE_MgCO2',
            'Avoided_Emissions_BE_Intracell_STD_MgCO2',
        ]
        
        # Ensure only existing columns are selected
        cols_final = [c for c in cols_to_keep if c in df.columns]
        
        df_export = df[cols_final].copy()
        df_export.to_excel(filename, index=False)
        print(f"Data successfully exported to {filename}")
    except Exception as e:
        print(f"Error exporting data: {e}")

