#*5. Creating preprocess Data function (Yield Conversion)

def preprocess_yields(df):
    try:
        # 1. Clean Area Data
        if 'Coca_2022' in df.columns:
            df['Coca_2022'] = df['Coca_2022'].astype(float)
            df.loc[df['Coca_2022'] < 0.067, 'Coca_2022'] = 0

        # 2. Convert GAEZ Output to Total Cane Mass
        # Applying factor 10 (GAEZ Doc p.156) to convert Sugar Index to Cane Mass
        GAEZ_SUGAR_TO_CANE_FACTOR = 10 
        
        if 'Yield_SugarCane' in df.columns:
            # Convert Yield to float
            df['Yield_SugarCane'] = df['Yield_SugarCane'].astype(float)
            
            # Apply Conversion Factor (Kg Sugar -> Kg Cane)
            df['Cane_Yield_Kg_ha'] = df['Yield_SugarCane'] * GAEZ_SUGAR_TO_CANE_FACTOR
            df['Cane_Intracell_STD_Kg_ha']   = df['Intracell_STD_SugarCane'] * GAEZ_SUGAR_TO_CANE_FACTOR
            
            # Calculate Total Potential Biomass per Grid Cell (Mg)
            # (Kg/ha * ha) / 1000 = Mg
            df['Total_Cane_Mg'] = (df['Cane_Yield_Kg_ha'] * df['Coca_2022']) / 1000
            df['Total_Cane_Intracell_STD_Mg'] = (df['Cane_Intracell_STD_Kg_ha'] * df['Coca_2022']) / 1000
            
        else:
            raise ValueError("Column 'Yield_SugarCane' not found in input.")

        print("Preprocessing completed: Converted to Total Cane Mass (Mg).")
        
    except Exception as e:
        print(f"Error during preprocessing: {e}")
    return df

# Run Preprocessing
